import type { IntegrationAction } from "@fragno-dev/backoffice-api/v0/integrations";

import { BackofficeOperationError } from "@/backoffice-runtime/operation-error";
import type { BackofficeStateBackend } from "@/fragno/codemode/state-backend";
import { jsonSchemaToJSDocTypedefs, type JsonSchemaObject } from "@/lib/zod/zod-formatter";

/** Marks files this generator owns, so regeneration never replaces a hand-written module. */
const GENERATED_HEADER = "// Generated by integrations.generateClient";

/** The module's own helper; an action with the same name is renamed instead. */
const INVOKE_ACTION = "invokeAction";

const RESERVED_WORDS = new Set([
  "arguments",
  "await",
  "break",
  "case",
  "catch",
  "class",
  "const",
  "continue",
  "debugger",
  "default",
  "delete",
  "do",
  "else",
  "enum",
  "eval",
  "export",
  "extends",
  "false",
  "finally",
  "for",
  "function",
  "if",
  "implements",
  "import",
  "in",
  "instanceof",
  "interface",
  "let",
  "new",
  "null",
  "package",
  "private",
  "protected",
  "public",
  "return",
  "static",
  "super",
  "switch",
  "this",
  "throw",
  "true",
  "try",
  "typeof",
  "var",
  "void",
  "while",
  "with",
  "yield",
]);

type IntegrationClientExport = { name: string; actionId: string };

function functionNameForAction(actionId: string) {
  const [first = "", ...rest] = actionId.split(/[^A-Za-z0-9]+/u).filter(Boolean);
  const name = [
    `${first.charAt(0).toLowerCase()}${first.slice(1)}`,
    ...rest.map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`),
  ].join("");
  const identifier = /^[0-9]/u.test(name) ? `_${name}` : name || "action";
  return RESERVED_WORDS.has(identifier) ? `${identifier}_` : identifier;
}

function renderSchemaTypedefs(schema: IntegrationAction["inputSchema"], typeName: string) {
  // Boolean schemas accept any JSON value or none at all.
  if (typeof schema === "boolean") {
    return [`/** @typedef {${schema ? "JsonValue" : "never"}} ${typeName} */`];
  }
  // Action schemas are authoritative JSON Schema objects published by their source.
  return jsonSchemaToJSDocTypedefs(schema as JsonSchemaObject, typeName);
}

function renderComment(lines: string[]) {
  const body = lines.join("\n").replaceAll("*/", "*\\/").split("\n");
  return ["/**", ...body.map((line) => (line ? ` * ${line}` : " *")), " */"].join("\n");
}

/**
 * Renders one typed function per action, each calling `integrations.execute`. The functions add no
 * validation of their own: execution validates input and output against the live contracts.
 */
function renderIntegrationClientModule(
  connectionId: string,
  actions: readonly IntegrationAction[],
): { source: string; exports: IntegrationClientExport[] } {
  const usedNames = new Set([INVOKE_ACTION]);
  const exports: IntegrationClientExport[] = [];
  const sections = actions.map((action) => {
    const baseName = functionNameForAction(action.id);
    let name = baseName;
    for (let suffix = 2; usedNames.has(name); suffix += 1) {
      name = `${baseName}${suffix}`;
    }
    usedNames.add(name);
    exports.push({ name, actionId: action.id });
    const typeName = `${name.charAt(0).toUpperCase()}${name.slice(1)}`;
    const inputTypeName = `${typeName}Input`;
    const outputTypeName = `${typeName}Output`;
    const { validation } = action;
    return [
      // An unchecked input schema may not describe what the service accepts, so it types nothing.
      ...(validation.kind === "checked"
        ? renderSchemaTypedefs(action.inputSchema, inputTypeName)
        : [`/** @typedef {Record<string, unknown>} ${inputTypeName} */`]),
      ...renderSchemaTypedefs(action.outputSchema, outputTypeName),
      renderComment([
        `${action.label}. ${action.description}`.trim(),
        ...(validation.kind === "unchecked"
          ? [
              "",
              `Unchecked: ${validation.reason} Input and output are not validated; the service alone rejects bad input.`,
            ]
          : []),
        "",
        `Action ${JSON.stringify(action.id)} of ${connectionId}.`,
        `@param {${inputTypeName}} input`,
        `@returns {Promise<${outputTypeName}>}`,
      ]),
      `export async function ${name}(input) {`,
      `  return await ${INVOKE_ACTION}(${JSON.stringify(action.id)}, input, ${validation.kind === "unchecked"});`,
      "}",
    ].join("\n");
  });

  const source = [
    `${GENERATED_HEADER} for ${connectionId}. Regenerating replaces this file;`,
    "// keep your own helpers in another module. Each function calls integrations.execute, which",
    "// validates input and output against the connection's live action contracts.",
    "",
    "/**",
    " * @param {string} actionId",
    " * @param {unknown} input",
    " * @param {boolean} unchecked",
    " * @returns {Promise<any>}",
    " */",
    `async function ${INVOKE_ACTION}(actionId, input, unchecked) {`,
    "  return await integrations.execute({",
    `    connectionId: ${JSON.stringify(connectionId)},`,
    "    actionId,",
    "    input: /** @type {JsonValue} */ (input),",
    "    unchecked,",
    "  });",
    "}",
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
  return { source, exports };
}

/**
 * Writes a connection's generated client module. Only a previously generated client is replaced,
 * so a mistyped output path cannot destroy a hand-written file.
 */
export async function writeIntegrationClientModule(input: {
  connectionId: string;
  out: string;
  actions: readonly IntegrationAction[];
  state: BackofficeStateBackend;
}): Promise<{ path: string; exports: IntegrationClientExport[] }> {
  if (!input.out.startsWith("/")) {
    throw new BackofficeOperationError("invalid_request", "Client output path must be absolute.");
  }
  const path = input.state.resolvePath("/workspace", input.out);
  if (!path.startsWith("/workspace/") || !path.endsWith(".js") || path.endsWith(".workflow.js")) {
    throw new BackofficeOperationError(
      "invalid_request",
      `Client output must be a .js module under /workspace, not ${input.out}.`,
    );
  }
  const existing = await input.state.stat(path);
  if (
    existing &&
    (existing.type !== "file" || !(await input.state.readFile(path)).startsWith(GENERATED_HEADER))
  ) {
    throw new BackofficeOperationError(
      "conflict",
      `${path} exists and was not generated by integrations.generateClient; choose another output path.`,
    );
  }
  const { source, exports } = renderIntegrationClientModule(input.connectionId, input.actions);
  await input.state.writeFile(path, source);
  return { path, exports };
}
